#!/usr/bin/env python3
"""Generate the GENERATED parts of each skill pack - never SKILL.md, which is authored (spec + questions):
  skills/<name>/references/policy.md  policy text INJECTED from the live RAG index (the model is asked to judge against it)
plus skills/README.md (catalogue) and docs/skills/coverage.md (scenario x skill matrix from real runs)."""
import json
import tempfile
from pathlib import Path

import yaml

from finagent.config import load_settings
from finagent.evaluation import EVAL_OVERRIDES
from finagent.services import build_app
from finagent.skills.base import REGISTRY, resolve_compliance
from finagent.skills.pack import load_pack
from finagent.skills.testing import SkillHarness

ROOT = Path(__file__).resolve().parents[2]
base = load_settings()
s = base.with_overrides({**EVAL_OVERRIDES, "app.data_dir": tempfile.mkdtemp(prefix="finagent-docs-")})
app = build_app(s)
harness = SkillHarness(app)
results = {(r.skill, r.fixture_id): r for r in harness.run_all()}
steps = {st.skill: st for st in app.pipeline.steps}
index_chunks = app.retriever.index.chunks

for name, spec in REGISTRY.items():
    d = ROOT / "skills" / name
    d.mkdir(parents=True, exist_ok=True)
    injected = resolve_compliance(index_chunks, spec.compliance_refs)
    pack = load_pack(name)
    comp = [f"# Policy sections for `{name}`\n",
            f"_Injected from the live policy index (index {app.retriever.index_version}). Generated - do not edit; run "
            "`finagent skills docs`. The skill's questions are judged against this text._\n"]
    for c in injected:
        comp.append(f"## {c['document_id']} v{c['version']} - {c['section']}\n\n`{c['chunk_id']}` (trust: {c['trust']})\n\n{c['text']}\n")
    if not injected:
        comp.append("_No static policy sections: this skill cites the sections its checks cite._\n")
    (d / "references").mkdir(exist_ok=True)
    (d / "references" / "policy.md").write_text("\n".join(comp))
    (d / "compliance.md").unlink(missing_ok=True)
    (d / "CARD.md").unlink(missing_ok=True)          # removed: SKILL.md + the catalogue carry these facts

# index
rows = ["# Skills catalogue", "", "_Generated by `finagent skills docs`._", "",
        "Every skill is a pack with the same contract: `SKILL.md` (spec, authored), `references/` (policy + external docs), "
        "`tests/`. Every skill runs its deterministic script. Skills with `code+llm` also ask fixed questions: code "
        "collects the evidence, a small model answers (a larger one gives a second opinion on concerns), code checks the "
        "quotes and maps the answers to verdicts (caution only). "
        "Order: `config/workflow.yaml`. Design: [docs/skills.md](../docs/skills.md).", "",
        "| Skill | Kind | Execution | Mandatory | Stage / when | Questions | Fixtures |", "|---|---|---|---|---|---|---|"]
for name, spec in REGISTRY.items():
    st = steps.get(name)
    fx = [r for (sk, _), r in results.items() if sk == name]
    pk = load_pack(name).spec
    rows.append(f"| [`{name}`]({name}/SKILL.md) | {spec.kind} | {pk.execution} | {'yes' if spec.mandatory else ''} | "
                f"{(st.stage + ' / ' + st.when) if st else 'parser registry'} | {', '.join(q.id for q in pk.questions) or '-'} | "
                f"{sum(r.passed for r in fx)}/{len(fx)} |")
(ROOT / "skills" / "README.md").write_text("\n".join(rows) + "\n")

m = harness.coverage_matrix()
cov = ["# Skill x scenario coverage", "", "_Generated by `finagent skills docs` from real runs of every scenario's evidence "
       "through every planned skill._ `VOTE:HOLD` etc. = the skill voted that outcome; `FAIL`/`UNKNOWN` = a failing/unknown "
       "finding without a vote; `PASS` = all findings passed; `-` = not planned for this case (condition false).", "",
       "| Case | " + " | ".join(m["skills"]) + " |", "|---" * (len(m["skills"]) + 1) + "|"]
for r in m["rows"]:
    cov.append(f"| {r['case_id']} | " + " | ".join(r["cells"][sk] for sk in m["skills"]) + " |")
(ROOT / "docs" / "skills" / "coverage.md").write_text("\n".join(cov) + "\n")
print(f"skills docs: {len(REGISTRY)} skills, {len(results)} fixtures ({sum(r.passed for r in results.values())} passing)")
