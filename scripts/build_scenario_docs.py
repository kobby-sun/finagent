#!/usr/bin/env python3
"""Generate docs/scenarios/*.md (one per scenario + index) with the ACTUAL evaluation result of each,
and docs/samples/*.md transcripts (successful approval flow + exception flow)."""
import json
import tempfile
from pathlib import Path

from finagent.config import load_settings
from finagent.evaluation import run_evaluation

ROOT = Path(__file__).resolve().parents[1]
sc = json.loads((ROOT / "mock_data" / "scenarios.json").read_text())
report = run_evaluation(load_settings().with_overrides({"app.data_dir": tempfile.mkdtemp(prefix="finagent-scen-")}), keep_dir=True)
res = {r["case_id"]: r for r in report["results"]}
out = ROOT / "docs" / "scenarios"
out.mkdir(parents=True, exist_ok=True)

STEP_TEXT = {
    "start": lambda s: f"Start run{' (simulate crash after ' + s['crash_after'] + ')' if s.get('crash_after') else ''} -> expect `{s['expect_status']}`"
                       + (f", outcome `{s['expect_outcome']}`" if s.get("expect_outcome") else "")
                       + (f", primary exception `{s['expect_primary_exception']}`" if s.get("expect_primary_exception") else "")
                       + "".join(f"<br/>&nbsp;&nbsp;- {k.replace('expect_', '')}: `{v}`" for k, v in s.items()
                                 if k.startswith("expect_") and k not in ("expect_status", "expect_outcome", "expect_primary_exception")),
    "decide": lambda s: f"`{s['decision']}` by `{s['approver_id']}`" + (f" (callback `{s['callback_id']}`)" if s.get("callback_id") else "")
                        + (f" (simulate crash after {s['crash_after']})" if s.get("crash_after") else "")
                        + f" -> HTTP {s['expect_http']}" + (f", run `{s['expect_status']}`" if s.get("expect_status") else "")
                        + (" (replayed response)" if s.get("expect_replayed") else ""),
    "resume": lambda s: f"Resume run -> `{s['expect_status']}`",
    "assert": lambda s: "Assert " + ", ".join(f"{k}={v}" for k, v in s.items() if k != "op"),
    "add_evidence": lambda s: f"Add evidence (po_ref `{s.get('po_ref')}`) -> new attempt `{s['expect_status']}`",
    "start_invalid": lambda s: f"Submit invalid request -> HTTP {s['expect_http']}",
    "check": lambda s: "Check " + ", ".join(f"{k.replace('expect_', '')}={v}" for k, v in s.items() if k != "op"),
}

idx = ["# Scenarios", "", f"Generated by `python scripts/build_scenario_docs.py` from `mock_data/scenarios.json`; results are from "
       f"evaluation `{report['summary']['eval_id']}` (provider `{report['summary']['provider']}`): "
       f"**{report['summary']['passed']}/{report['summary']['scenarios']} scenarios, "
       f"{report['summary']['checks_passed']}/{report['summary']['checks']} checks passed**.", "",
       "Required cases from the brief are FIN-001..FIN-005, `edge` cases cover single edge conditions, and `combined` cases "
       f"(FIN-043+) stack several edge conditions at once. The mock clock is frozen at `{sc['clock']}`.", "",
       "**Every scenario is checked for:**",
       "- outcome, status and primary exception;",
       "- the step the workflow **exits** at (and steps it must never reach);",
       "- tools that must or must not be called;",
       "- required audit events (retries, model guard, approval refusals, replays);",
       "- exceptions, warnings (risk indicators) and unknowns that must be recorded;",
       "- reasoning-trace entries and emitted webhooks.",
       "",
       "**Global invariants applied to all scenarios:** the exit step matches the status; held or escalated cases never create an "
       "approval or call the posting tool; every executed control has a reasoning entry; no untrusted or superseded policy is cited; "
       "no full bank account number appears in the audit log. "
       "`finagent eval --diagrams png` draws each scenario's final run.", "", "| Case | Kind | Title | Input | Expected | Result |", "|---|---|---|---|---|---|"]
for s in sc["scenarios"]:
    r = res[s["case_id"]]
    exp = s["expected"]
    idx.append(f"| [{s['case_id']}]({s['case_id']}.md) | {s['kind']} | {s['title']} | {s['input_format']} | "
               f"{exp.get('outcome', exp.get('status'))} / {exp.get('pool_status', exp.get('http', ''))} | {'PASS' if r['passed'] else 'FAIL'} |")
    req = json.loads((ROOT / s["request_file"]).read_text())
    md = [f"# {s['case_id']} — {s['title']}", "", f"**Kind:** {s['kind']}  |  **Input format:** {s['input_format']}  |  "
          f"**Policies:** {', '.join(s['policies'])}", "", "## Signals", "", s["signals"], ""]
    if s.get("notes_md"):
        md += [s["notes_md"], ""]
    md += ["## Request", "", "```json", json.dumps({k: v for k, v in req.items() if k != "attachments"}, indent=2), "```", "",
           "Attachments: " + (", ".join(f"`{a['filename']}` ({a['content_type']}, source={a.get('source')})" for a in req.get("attachments", [])) or "none")
           + f" — see `mock_data/cases/{s['case_id']}/attachments/`.", "",
           "## Expected control behaviour", "", "```json", json.dumps(exp, indent=2), "```", "", "## Steps", ""]
    md += [f"{i}. {STEP_TEXT[st['op']](st)}" for i, st in enumerate(s["steps"], 1)]
    md += ["", "## Run it", "", "```bash", f"finagent start --case {s['case_id']}", "finagent approvals --status PENDING --explain   # if awaiting approval",
           "finagent approve <approval_id> --approver <user> --callback-id <id>", f"finagent eval --cases {s['case_id']}", "```", "",
           f"## Latest evaluation result: {'PASS' if r['passed'] else 'FAIL'}", "", "| Check | Result | Detail |", "|---|---|---|"]
    md += [f"| {c['check']} | {'pass' if c['passed'] else '**FAIL**'} | {str(c['detail']).replace('|', '/')[:120]} |" for c in r["checks"]]
    (out / f"{s['case_id']}.md").write_text("\n".join(md) + "\n")
(out / "README.md").write_text("\n".join(idx) + "\n")
print(f"wrote {len(sc['scenarios'])} scenario docs")
